#!/usr/bin/env node
// Turn `claude plugin eval --json` result files into evals/REPORT.md.
// Usage: node scripts/eval-report.mjs <result.json>... > evals/REPORT.md
import { readFileSync } from 'node:fs';

const files = process.argv.slice(2);
if (!files.length) { console.error('usage: node scripts/eval-report.mjs <result.json>...'); process.exit(1); }

const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN);
const pct = (x) => (Number.isNaN(x) ? '-' : `${Math.round(x * 100)}%`);
const skills = new Map();
let cost = 0, version = '', runs = new Set(), started = '';

for (const f of files) {
  const d = JSON.parse(readFileSync(f, 'utf8'));
  cost += d.costUsd || 0; version = d.claudeVersion; started = started || d.startedAt;
  for (const c of d.cases) {
    const m = c.name.match(/^(.*?)-(no-trigger|trigger|task)-(\d+)$/);
    if (!m) continue;
    const [, skill, kind] = m;
    if (!skills.has(skill)) skills.set(skill, { trigger: [], 'no-trigger': [], task: [] });
    runs.add((c.arms.with || []).length);
    const withRuns = (c.arms.with || []).map((r) => r.score ?? 0);
    const withoutRuns = (c.arms.without || []).map((r) => r.score ?? 0);
    skills.get(skill)[kind].push({ name: c.name, with: mean(withRuns), without: mean(withoutRuns), runOk: withRuns.filter((s) => s >= 1).length, runs: withRuns.length, errors: (c.arms.with || []).filter((r) => r.error).length });
  }
}

const out = [];
out.push('# Eval results', '');
out.push(`Claude Code ${version}, run ${started.slice(0, 10)}, ${[...runs].join('/')} runs per case and arm, list-price cost $${cost.toFixed(2)}. Generated by \`scripts/eval-report.mjs\` from \`claude plugin eval --json\` output. The table is generated; the notes at the end are written by hand.`, '');
out.push('- **Trigger**: share of runs where the skill loaded on a prompt that should load it (one arm, plugin installed).');
out.push('- **No-trigger**: share of runs where it stayed out of a near-miss prompt.');
out.push('- **Task with / without**: mean grader score (0-1) on a real task, with the plugin and with no plugin. Δ is the difference.', '');
out.push('| Skill | Trigger | No-trigger | Task with | Task without | Δ |', '|---|---|---|---|---|---|');
for (const [skill, k] of [...skills].sort()) {
  const rate = (xs) => { const ok = xs.reduce((a, x) => a + x.runOk, 0), n = xs.reduce((a, x) => a + x.runs, 0); return n ? `${pct(ok / n)} (${ok}/${n})` : 'n/a'; };
  const tw = mean(k.task.map((t) => t.with)), two = mean(k.task.map((t) => t.without).filter((x) => !Number.isNaN(x)));
  const delta = Number.isNaN(two) ? '-' : `${tw - two >= 0 ? '+' : ''}${(tw - two).toFixed(2)}`;
  out.push(`| ${skill} | ${k.trigger.length ? rate(k.trigger) : 'n/a (manual only)'} | ${rate(k['no-trigger'])} | ${Number.isNaN(tw) ? '-' : tw.toFixed(2)} | ${Number.isNaN(two) ? '-' : two.toFixed(2)} | ${delta} |`);
}
out.push('', '## Cases below 100%', '');
const weak = [...skills].flatMap(([, k]) => [...k.trigger, ...k['no-trigger'], ...k.task]).filter((c) => c.with < 1);
out.push(weak.length ? weak.map((c) => `- \`${c.name}\`: with ${c.with.toFixed(2)}${Number.isNaN(c.without) ? '' : `, without ${c.without.toFixed(2)}`}${c.errors ? ` (${c.errors} run(s) ended with an error, e.g. max turns)` : ''}`).join('\n') : 'None.');
console.log(out.join('\n'));
